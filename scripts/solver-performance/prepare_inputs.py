"""Prepare the measurement inputs of the language 0.4 without a compiler or solver.

The representatives are the twelve reviewed cases of tests/integration/solver-0.4, copied with
the bytes Git holds for them (LF), whatever the checkout wrote. The four scale families are
generated here, UTF-8 with LF and a final newline. A file of 0.4 loads the standard packages the
command holds, so no package files are prepared. Every byte is checked against the manifest.
"""
import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath

FAMILIES = ('chain', 'diffmirror', 'star', 'distances')
SIZES = tuple(2**power for power in range(1, 11))
REPRESENTATIVES = 12
REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / 'tests/performance'
HEADER = '* @RNL(type="header") { @USE-PACKAGE(name="rnl-std-all", version="0.4"); @VERSION("0.4") }'


def generate(family, n):
    if family not in FAMILIES or type(n) is not int or n not in SIZES:
        raise ValueError('Use a family of the manifest and n = 2, 4, ..., 1024')
    lines = [f'* Synthetic {family}; n={n}; generated by prepare_inputs.py', HEADER]
    if family == 'diffmirror':
        lines += ['.model nch nmos level=1', '.model pch pmos level=1']
        for i in range(n):
            lines += [f'M{i}a x{i} inp{i} tail{i} vss nch W=2u L=0.5u',
                      f'M{i}b out{i} inn{i} tail{i} vss nch W=2u L=0.5u',
                      f'M{i}c x{i} x{i} vdd vdd pch W=4u L=0.5u',
                      f'M{i}d out{i} x{i} vdd vdd pch W=4u L=0.5u',
                      f'M{i}t tail{i} vbias vss vss nch W=4u L=1u']
    elif family == 'star':
        lines += [f'R{i} hub leaf{i} 1k' for i in range(n)]
    else:
        count = 2*n if family == 'distances' else n
        lines += [f'R{i} q{i} q{i+1} 1k' for i in range(count)]
    lines.append('* @RNL {')
    members = ' '.join(f'#R{i}' for i in range(n))
    if family == 'chain':
        lines.append(f'*   {{{members}}} @AS $SIGNAL_FLOW;')
    elif family == 'star':
        lines += [f'*   {{{members}}} @ALIGN("y");',
                  f'*   {{{members}}} @ORDER("left-to-right");']
    elif family == 'distances':
        for i in range(n):
            lines += [f'*   #R{2*i} @PLACE({20*i}, 0);',
                      f'*   #R{2*i+1} @PLACE(y=0);',
                      f'*   #R{2*i} #R{2*i+1} @DISTANCE("left-to-right", min=8, max=12);']
    else:
        lines += ['*   # @SELECT-INSTANCE(model="nch") => @SET-SYMBOL $NMOS;',
                  '*   # @SELECT-INSTANCE(model="pch") => @SET-SYMBOL $PMOS;',
                  '*   &vdd @ADD-TO $SUPPLY_NET_SET;',
                  '*   &vss @ADD-TO $GROUND_NET_SET;']
        for i in range(n):
            lines += [f'*   %g{i} = {{#M{i}a #M{i}b #M{i}c #M{i}d #M{i}t}} @GROUP;',
                      f'*   %dp{i} = #M{i}a(left) #M{i}b(right) #M{i}t(tail) @AS $DIFFERENTIAL_PAIR_N;',
                      f'*   %cm{i} = #M{i}c(ref) #M{i}d(out) @AS $CURRENT_MIRROR_P;',
                      f'*   #M{i}c(left) #M{i}d(right) #M{i}t(axis) @AS $MIRRORED_LAYOUT;',
                      f'*   #M{i}t {{#M{i}a #M{i}b}} @DISTANCE("bottom-to-top", min=2);',
                      f'*   {{#M{i}a #M{i}b}} {{#M{i}c #M{i}d}} @DISTANCE("bottom-to-top", min=2);']
        groups = ' '.join(f'%g{i}' for i in range(n))
        lines.append(f'*   {{{groups}}} @AS $SIGNAL_FLOW;')
    lines += ['*   # @SELECT-NET => @ROUTE-NET', '* }', '.end']
    return ('\n'.join(lines) + '\n').encode('utf-8')


def safe_path(path):
    value = PurePosixPath(path)
    if value.is_absolute() or '..' in value.parts or '\\' in path or ':' in path:
        raise ValueError('Fixture path must stay inside its root: ' + path)
    return value


def checked(data, item):
    if hashlib.sha256(data).hexdigest() != item['sha256'] or ('bytes' in item and len(data) != item['bytes']):
        raise RuntimeError('Input bytes differ from the manifest: ' + item.get('input', item.get('path', 'manifest')))
    return data


def representative_bytes(item):
    # The bytes Git holds (LF): a Windows checkout may have written CRLF.
    return (REPO/safe_path(item['source'])).read_bytes().replace(b'\r\n', b'\n')


def manifest():
    value = json.loads((SOURCE/'manifest.json').read_text(encoding='utf-8'))
    if value.get('schema_version') != 2 or value.get('language') != '0.4':
        raise RuntimeError('Expected the manifest of schema 2, for the language 0.4')
    if len(value['representative']) != REPRESENTATIVES:
        raise RuntimeError(f'Expected {REPRESENTATIVES} representatives')
    expected = [(family, n) for family in FAMILIES for n in SIZES]
    if [(item['family'], item['n']) for item in value['synthetic']] != expected:
        raise RuntimeError('Synthetic queue changed')
    return value


def fixture_bytes(value):
    for item in value['representative']:
        yield item['input'], checked(representative_bytes(item), item)
    for item in value['synthetic']:
        yield item['input'], checked(generate(item['family'], item['n']), item)


def prepare(output):
    value = manifest()
    output = Path(output).resolve()
    # Build outside the repository, so that no generated input is ever committed by mistake.
    if output.is_relative_to(REPO):
        raise ValueError('Use an output directory outside the repository')
    output.mkdir(parents=True, exist_ok=False)
    for path, data in fixture_bytes(value):
        destination = output/safe_path(path)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)
    (output/'manifest.json').write_bytes((SOURCE/'manifest.json').read_bytes())
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True, help='New directory outside the repository')
    args = parser.parse_args()
    prepare(args.output)
    print(f'Prepared {REPRESENTATIVES} representatives and {len(FAMILIES)*len(SIZES)} generated inputs; zero solver calls')


if __name__ == '__main__':
    main()
