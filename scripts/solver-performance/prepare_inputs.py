"""Recreate the frozen measurement inputs without a compiler or solver.

All generated files are UTF-8 with LF and a final newline. The title intentionally
keeps the historical generator name: it is part of the original input bytes.
Git reads are offline; the caller must fetch the manifest's immutable commits.
"""
import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import subprocess

FAMILIES = ('chain', 'diffmirror', 'star', 'disjunctions')
SIZES = tuple(2**power for power in range(1, 11))
REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / 'tests/performance'


def generate(family, n):
    if family not in FAMILIES or type(n) is not int or n not in SIZES:
        raise ValueError('Use a frozen family and n = 2, 4, ..., 1024')
    lines = [f'* Synthetic {family}; n={n}; generated by prepare_inputs.py',
             '* @RNL(type="header") { @VERSION("0.3") }']
    if family == 'diffmirror':
        lines += ['.model nch nmos level=1', '.model pch pmos level=1']
        for i in range(n):
            lines += [f'M{i}a x{i} inp{i} tail{i} vss nch W=2u L=0.5u',
                      f'M{i}b out{i} inn{i} tail{i} vss nch W=2u L=0.5u',
                      f'M{i}c x{i} x{i} vdd vdd pch W=4u L=0.5u',
                      f'M{i}d out{i} x{i} vdd vdd pch W=4u L=0.5u',
                      f'M{i}t tail{i} vbias vss vss nch W=4u L=1u']
    elif family == 'star':
        lines += [f'R{i} hub leaf{i} 1k' for i in range(n)]
    else:
        count = 2*n if family == 'disjunctions' else n
        lines += [f'R{i} q{i} q{i+1} 1k' for i in range(count)]
    lines.append('* @RNL {')
    members = ' '.join(f'#R{i}' for i in range(n))
    if family == 'chain':
        lines.append(f'*   {{{members}}} @AS $FLOW;')
    elif family == 'star':
        lines += [f'*   {{{members}}} @ALIGN("y");',
                  f'*   {{{members}}} @ORDER("left-to-right");']
    elif family == 'disjunctions':
        for i in range(n):
            lines += [f'*   #R{2*i} @PLACE({20*i}, 0);',
                      f'*   #R{2*i+1} @PLACE(y=0);',
                      f'*   #R{2*i} #R{2*i+1} @DISTANCE("x", min=8, max=12);']
    else:
        lines += ['*   # @SELECT-INSTANCE(model="nch") => @SET-SYMBOL $NMOS;',
                  '*   # @SELECT-INSTANCE(model="pch") => @SET-SYMBOL $PMOS;',
                  '*   &vdd @ADD-TO $SUPPLY_NET_SET;',
                  '*   &vss @ADD-TO $GROUND_NET_SET;']
        for i in range(n):
            lines += [f'*   %g{i} = {{#M{i}a #M{i}b #M{i}c #M{i}d #M{i}t}} @GROUP;',
                      f'*   %dp{i} = #M{i}a(in_p) #M{i}b(in_n) #M{i}t(tail) @AS $DIFFERENTIAL_PAIR;',
                      f'*   %cm{i} = #M{i}c(ref) #M{i}d(out) @AS $CURRENT_MIRROR;',
                      f'*   %axis{i} = (_, _);',
                      f'*   #M{i}a(a) #M{i}b(b) %axis{i}(axis) @AS $MIRRORED;',
                      f'*   #M{i}c(a) #M{i}d(b) %axis{i}(axis) @AS $MIRRORED;',
                      f'*   #M{i}t {{#M{i}a #M{i}b}} @DISTANCE("bottom-to-top", min=2);',
                      f'*   {{#M{i}a #M{i}b}} {{#M{i}c #M{i}d}} @DISTANCE("bottom-to-top", min=2);']
        groups = ' '.join(f'%g{i}' for i in range(n))
        lines.append(f'*   {{{groups}}} @AS $FLOW;')
    lines += ['*   $WIRE_NET_SET @ROUTE', '* }', '.end']
    return ('\n'.join(lines) + '\n').encode('utf-8')


def git_bytes(commit, path):
    if not re.fullmatch('[0-9a-f]{40}', commit):
        raise ValueError('Source commit must be a full immutable SHA')
    safe_path(path)
    try:
        return subprocess.check_output(['git', 'show', f'{commit}:{path}'], cwd=REPO)
    except subprocess.CalledProcessError as error:
        raise RuntimeError(f'Cannot read pinned input. Fetch commit {commit} before preparing fixtures') from error


def safe_path(path):
    value = PurePosixPath(path)
    if value.is_absolute() or '..' in value.parts or '\\' in path or ':' in path:
        raise ValueError('Fixture path must stay inside its root: ' + path)
    return value


def checked(data, item):
    if hashlib.sha256(data).hexdigest() != item['sha256'] or ('bytes' in item and len(data) != item['bytes']):
        raise RuntimeError('Frozen input bytes differ: ' + item.get('input', item.get('path', 'manifest')))
    return data


def manifest():
    value = json.loads((SOURCE/'manifest.json').read_text(encoding='utf-8'))
    history = value['historical_source']
    original = checked(git_bytes(history['commit'], history['manifest_path']), history)
    old = json.loads(original)
    # Retain the entire previous selection and every input hash, not just M04.
    if any(value.get(key) != previous for key, previous in old.items()):
        raise RuntimeError('Historical manifest selection/parameters changed')
    if value['library_source']['commit'] != value['source_base']:
        raise RuntimeError('Standard packages must use the historical source baseline')
    expected = [(family, n) for family in FAMILIES for n in SIZES]
    if [(item['family'], item['n']) for item in value['synthetic']] != expected:
        raise RuntimeError('Frozen synthetic queue changed')
    return value


def fixture_bytes(value):
    for item in value['representative']:
        path = item['input']
        yield path, checked((SOURCE/safe_path(path)).read_bytes(), item)
    for item in value['synthetic']:
        yield item['input'], checked(generate(item['family'], item['n']), item)
    library = value['library_source']
    if library['line_endings'] != 'crlf':
        raise RuntimeError('The historical package copies used CRLF')
    for item in value['library']:
        relative = PurePosixPath(item['path']).relative_to('library')
        path = str(PurePosixPath(library['path'])/relative)
        # The previous Windows campaign froze CRLF working-tree copies of LF
        # Git blobs. Reproduce that explicit byte convention on every platform.
        data = git_bytes(library['commit'], path).replace(b'\r\n', b'\n').replace(b'\n', b'\r\n')
        yield item['path'], checked(data, item)


def prepare(output):
    value = manifest()
    output = Path(output).resolve()
    # Build outside the repository: never recreate the removed vendored trees.
    if output.is_relative_to(REPO):
        raise ValueError('Use an output directory outside the repository')
    output.mkdir(parents=True, exist_ok=False)
    for path, data in fixture_bytes(value):
        destination = output/safe_path(path)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)
    (output/'manifest.json').write_bytes((SOURCE/'manifest.json').read_bytes())
    (output/'canonical-main.json').write_bytes((SOURCE/'canonical-main.json').read_bytes())
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True, help='New directory outside the repository')
    args = parser.parse_args()
    prepare(args.output)
    print('Prepared 11 representatives, 40 generated inputs and 25 pinned packages; zero solver calls')


if __name__ == '__main__':
    main()
